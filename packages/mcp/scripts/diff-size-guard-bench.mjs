/**
 * Calibration benchmark for the diffDocs pre-flight size guard (issues #464 /
 * #465 / #582).
 *
 * The guard's caps (MCP_DIFF_MAX_NODES / MCP_DIFF_MAX_BYTES in src/lib/diff.ts)
 * exist to keep the SYNCHRONOUS diff block inside ~200ms for any ADMITTED pair.
 * They are therefore only ever as good as the measurement behind them: this
 * script runs the exact diffDocs precise pipeline (with the guard disabled via
 * the env knobs) over adversarial shapes at increasing sizes and prints the
 * measured time, so the caps can be re-derived whenever the algorithm changes.
 *
 * ADMISSIBILITY IS THE POINT. A cap may only be justified by inputs the guard
 * actually LETS THROUGH: a row the guard would REFUSE tells you nothing about the
 * budget it promises. Every row below therefore prints an ADMIT/refuse verdict
 * against the caps, and the corner docs (the ones that calibrate the node cap) are
 * generated by BINARY-SEARCHING the per-block text length so the doc lands JUST
 * UNDER the byte cap. (#582's first pass instead used
 * `charsPer = floor(bytes/paras) - 40`, which ignores the ~55 B of JSON overhead
 * per paragraph and so produced 13-15 KB corner docs — every one of them REFUSED
 * by the byte cap. Those numbers justified nothing; this generator replaces them.)
 *
 * Run:  node scripts/diff-size-guard-bench.mjs
 *
 * Shapes (each is a worst case of a different cost term):
 *  - sweep-XX%   : XX% of the blocks edited in place, the rest untouched. Cost is
 *                  dominated by the step-recreation loop, which deep-copies and
 *                  re-parses the WHOLE doc per changed op => ~ changedOps x docBytes.
 *  - rewrite     : every block changed. Same term, maxed out (it does NOT hit the
 *                  cheap degenerate branch of fastCreatePatch: blocks of the same
 *                  type with overlapping tokens still pair up 1:1).
 *  - corner-*    : a doc sitting just under the guard's BYTE cap with every block
 *                  rewritten -- the row that CALIBRATES MCP_DIFF_MAX_NODES.
 *  - single-*    : ONE text node of N chars, rewritten wholesale. The word diff is
 *                  bounded by #581's caps (recreateTransform is a few ms here), but
 *                  ChangeSet.addSteps re-diffs the replaced range internally -- and
 *                  #581 did NOT touch addSteps. This is what BINDS the byte cap, and
 *                  why #582 TIGHTENED it from 12 KiB to 4 KiB.
 *  - split-*     : the same byte budget spread over 2/3/8 text nodes -- byte-heavy
 *                  but node-light. Token DENSITY matters as much as byte count: the
 *                  `dense-*` rows use base36 counters (short unique tokens) and are the
 *                  true adversarial worst case at a given byte budget.
 *  - single-edit : the same big text node with a SMALL edit -- ~1-3ms, i.e. the
 *                  cost tracks REWRITTEN text, not document size.
 *  - wordbomb-N  : node-light, byte-heavy: N paragraphs of ~1.9k chars (just under
 *                  editor-ext's WORD_DIFF_MAX_CHARS), half of them edited => the
 *                  aggregate word-diff shape. Cheap; not what binds the byte axis.
 */

import { Node } from "@tiptap/pm/model";
import { ChangeSet, simplifyChanges } from "@tiptap/pm/changeset";
// Subpath, NOT the "@docmost/editor-ext" barrel: the barrel drags @tiptap/react ->
// prosemirror-view -> React into this package (see the note in src/lib/diff.ts).
import { recreateTransform as recreateNew } from "@docmost/editor-ext/dist/lib/recreate-transform/index.js";
import { docmostSchema } from "../build/lib/docmost-schema.js";

// The caps this script calibrates (keep in sync with src/lib/diff.ts).
const MAX_NODES = 200;
const MAX_BYTES = 4 * 1024;
const BUDGET_MS = 200;

// --- doc builders -----------------------------------------------------------
const t = (text) => ({ type: "text", text });
const para = (text) => ({ type: "paragraph", content: text ? [t(text)] : [] });
const doc = (content) => ({ type: "doc", content });

const words = (seed, i, n) =>
  Array.from({ length: n }, (_, w) => `${seed}${i}_${w}`).join(" ");

/** N paragraphs, `frac` of them edited in place (and a couple inserted/deleted). */
function sweep(n, frac, wordsPerPara = 8) {
  const oldBlocks = [];
  const newBlocks = [];
  const every = frac > 0 ? Math.max(1, Math.round(1 / frac)) : Infinity;
  for (let i = 0; i < n; i++) {
    const base = words("a", i, wordsPerPara);
    oldBlocks.push(para(base));
    if (i % every === 0) {
      // In-place edit: same block, different words (forces a text replace op).
      newBlocks.push(para(base.replace(/a(\d+)_0/, "zz$1_0") + " tail"));
    } else {
      newBlocks.push(para(base));
    }
  }
  // A mixed insert + delete so the array patch is not a pure 1:1 replace list.
  if (n > 4) {
    newBlocks.splice(1, 1); // delete
    newBlocks.splice(3, 0, para("brand new inserted block here")); // insert
  }
  return [doc(oldBlocks), doc(newBlocks)];
}

/** N paragraphs, every one of them rewritten. */
function rewrite(n, wordsPerPara = 8) {
  return [
    doc(Array.from({ length: n }, (_, i) => para(words("a", i, wordsPerPara)))),
    doc(Array.from({ length: n }, (_, i) => para(words("b", i, wordsPerPara)))),
  ];
}

/** N paragraphs of ~1.9k chars each; half of them edited (aggregate word diff). */
function wordbomb(n, charsPerPara = 1900) {
  const filler = (seed, i) => {
    let s = "";
    let w = 0;
    while (s.length < charsPerPara) s += `${seed}${i}_${w++} `;
    return s.slice(0, charsPerPara);
  };
  const oldBlocks = [];
  const newBlocks = [];
  for (let i = 0; i < n; i++) {
    const base = filler("a", i);
    oldBlocks.push(para(base));
    // Every other paragraph gets a scattered edit -> a real word diff over ~1.9k
    // chars; the untouched half keeps the doc out of the degenerate branch.
    newBlocks.push(
      para(i % 2 === 0 ? base.replace(/a/g, (m, o) => (o % 7 === 0 ? "q" : m)) : base),
    );
  }
  return [doc(oldBlocks), doc(newBlocks)];
}

/** `paras` paragraphs of `charsPer` chars each, seeded from `seed`. */
function paraDoc(paras, charsPer, seed) {
  const blocks = [];
  for (let i = 0; i < paras; i++) {
    let s = "";
    let w = 0;
    while (s.length < charsPer) s += `${seed}${i}_${w++} `;
    blocks.push(para(s.slice(0, charsPer)));
  }
  return doc(blocks);
}

const jsonBytes = (d) => JSON.stringify(d).length;

/**
 * The largest per-paragraph text length for which BOTH docs of a `paras`-block
 * pair still serialize to <= `budget` bytes. Binary-searched against the REAL
 * JSON.stringify size — the same measurement the guard itself makes — instead of
 * an arithmetic guess at the per-node overhead. Returns 0 when even 1-char
 * paragraphs cannot fit, i.e. that node count is UNREACHABLE under the byte cap.
 */
function fitCharsPerPara(paras, budget) {
  const fits = (c) =>
    Math.max(jsonBytes(paraDoc(paras, c, "a")), jsonBytes(paraDoc(paras, c, "b"))) <=
    budget;
  if (!fits(1)) return 0;
  let lo = 1;
  let hi = Math.ceil(budget / paras) + 8;
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    if (fits(mid)) lo = mid;
    else hi = mid - 1;
  }
  return lo;
}

/**
 * A doc pair with `paras` blocks, EVERY block rewritten, sized to land just under
 * the byte cap. Returns null when `paras` blocks cannot fit under the cap at all.
 */
function corner(paras, budget = MAX_BYTES) {
  const charsPer = fitCharsPerPara(paras, budget);
  if (charsPer === 0) return null;
  return [paraDoc(paras, charsPer, "a"), paraDoc(paras, charsPer, "b")];
}

/** One text node of `chars` chars, rewritten wholesale. */
function onehuge(chars = 100_000) {
  const mk = (seed) => {
    let s = "";
    let w = 0;
    while (s.length < chars) s += `${seed}${w++} `;
    return doc([para(s.slice(0, chars))]);
  };
  return [mk("a"), mk("b")];
}

/** `nodes` text nodes sharing a `bytes` budget, all rewritten (byte-heavy, node-light). */
function split(nodes, bytes) {
  const charsPer = fitCharsPerPara(nodes, bytes);
  return [paraDoc(nodes, charsPer, "a"), paraDoc(nodes, charsPer, "b")];
}

/**
 * The ADVERSARIAL byte-axis worst case: `nodes` text nodes packed to `budget` bytes
 * with the SHORTEST possible unique tokens (base36 counters). Token density, not
 * byte count alone, drives the cost — addSteps re-diffs the replaced range token by
 * token, so at a fixed byte budget more tokens = more work. This shape is ~40-60%
 * more expensive than the same bytes in ordinary prose-length words, and it is what
 * the byte cap must actually survive: the document is agent/user-authored, so the
 * attacker picks the density.
 */
function dense(nodes, budget) {
  const mk = (seed) => {
    const per = Math.floor(budget / nodes);
    const blocks = [];
    for (let i = 0; i < nodes; i++) {
      let s = "";
      let w = 0;
      // Grow this block until adding one more token would push it past its share.
      for (;;) {
        const next = `${seed}${i}${(w).toString(36)} `;
        if (jsonBytes(doc([para(s + next)])) > per) break;
        s += next;
        w++;
      }
      blocks.push(para(s));
    }
    return doc(blocks);
  };
  return [mk("a"), mk("b")];
}

// --- measurement ------------------------------------------------------------
function countNodes(d) {
  let n = 0;
  const v = (x) => {
    if (!x || typeof x !== "object") return;
    n++;
    if (Array.isArray(x.content)) for (const c of x.content) v(c);
  };
  v(d);
  return n;
}

/** The exact preciseDiffTally pipeline from src/lib/diff.ts, impl-pluggable. */
function precise(recreate, oldJson, newJson) {
  const oldNode = Node.fromJSON(docmostSchema, oldJson);
  const newNode = Node.fromJSON(docmostSchema, newJson);
  const tr = recreate(oldNode, newNode, {
    complexSteps: false,
    wordDiffs: true,
    simplifyDiff: true,
  });
  const cs = ChangeSet.create(oldNode).addSteps(tr.doc, tr.mapping.maps, []);
  return simplifyChanges(cs.changes, newNode).length;
}

function timed(fn, reps = 3) {
  let best = Infinity;
  for (let i = 0; i < reps; i++) {
    const s = performance.now();
    fn();
    best = Math.min(best, performance.now() - s);
  }
  return best;
}

/**
 * Time one pair and print it with the guard's ADMIT/refuse verdict. Only ADMIT
 * rows constrain the caps: a refused row never reaches the precise pipeline in
 * production, so its time is informational only — it shows what the guard is
 * SAVING us from.
 */
function run(label, pair, { reps = 3 } = {}) {
  if (pair === null) {
    console.log(`${label.padEnd(22)} (unreachable: cannot fit under the byte cap)`);
    return Infinity;
  }
  const [oldJson, newJson] = pair;
  const nodes = Math.max(countNodes(oldJson), countNodes(newJson));
  const bytes = Math.max(jsonBytes(oldJson), jsonBytes(newJson));
  const admitted = nodes <= MAX_NODES && bytes <= MAX_BYTES;
  let ms;
  try {
    ms = timed(() => precise(recreateNew, oldJson, newJson), reps);
  } catch (e) {
    console.log(`${label.padEnd(22)} threw: ${e.message}`);
    return Infinity;
  }
  console.log(
    `${label.padEnd(22)} nodes=${String(nodes).padStart(5)} bytes=${String(bytes).padStart(7)}` +
      `  ${ms.toFixed(1).padStart(8)}ms  ${admitted ? "ADMIT " : "refuse"}` +
      (admitted && ms > BUDGET_MS ? "  <-- ADMITTED AND OVER BUDGET" : ""),
  );
  return ms;
}

console.log(
  `caps: ${MAX_NODES} nodes / ${MAX_BYTES} bytes | budget: ${BUDGET_MS}ms (synchronous block)`,
);
console.log(
  "only ADMIT rows constrain the caps; refused rows show what the guard prevents\n",
);

/** Stop growing a shape once it is this far past budget (the point is made). */
const ABORT_MS = 1500;

console.log("== node axis: sweep (in-place edits, non-degenerate) ==");
for (const frac of [0.15, 0.3, 0.5, 0.8]) {
  for (const n of [150, 300, 450, 600, 900, 1200, 1800]) {
    const ms = run(`sweep-${Math.round(frac * 100)}%-n${n}`, sweep(n, frac), { reps: 2 });
    if (ms > ABORT_MS) break;
  }
  console.log("");
}

console.log("== node axis: full rewrite (control) ==");
for (const n of [150, 300, 600, 1200, 2000]) {
  run(`rewrite-n${n}`, rewrite(n), { reps: 2 });
}

console.log("\n== corner: the docs that CALIBRATE the node cap ==");
console.log(`(every block rewritten, sized to land JUST UNDER the ${MAX_BYTES}B cap)`);
for (const paras of [30, 50, 60, 68, 75, 100, 113]) {
  run(`corner-${2 * paras + 1}n`, corner(paras), { reps: 3 });
}
console.log("note: ~55B of JSON overhead per text block means only ~68 text blocks (~137");
console.log("      nodes) fit under the byte cap at all -- and even the CHEAPEST node shape");
console.log("      (empty paragraphs, ~21B/node) tops out at ~190 nodes. So the 200-node cap");
console.log("      is SUBSUMED by the byte cap: it cannot trip at the default MCP_DIFF_MAX_BYTES.");

console.log("\n== byte axis: ONE text node rewritten wholesale (BINDS the byte cap) ==");
for (const chars of [2000, 4000, 6000, 8000, 10_000, 12_000, 19_000, 40_000]) {
  run(`single-${chars}`, onehuge(chars), { reps: 2 });
}

console.log("\n== byte axis: same budget over 2/3/8 text nodes (worst admitted shape) ==");
for (const bytes of [4096, 6144, 8192, 12_288]) {
  for (const n of [2, 3, 8]) {
    run(`split-${n}n@${bytes}B`, split(n, bytes), { reps: 3 });
  }
  console.log("");
}

console.log("== byte axis: DENSE tokens -- the ADVERSARIAL worst case (picks the cap) ==");
for (const bytes of [4096, 5120, 6144, 8192, 12_288]) {
  for (const n of [1, 2, 3]) {
    run(`dense-${n}n@${bytes}B`, dense(n, bytes), { reps: 3 });
  }
  console.log("");
}

console.log("== byte axis: same node, SMALL edit (cost tracks CHANGED text) ==");
for (const chars of [4000, 8000, 16_000]) {
  const [a] = onehuge(chars);
  const text = a.content[0].content[0].text;
  const b = doc([para(text.replace("a10 ", "a10 INSERTED "))]);
  run(`single-edit-${chars}`, [a, b], { reps: 2 });
}

console.log("\n== byte axis: aggregate word-diff (node-light, byte-heavy) ==");
for (const n of [4, 8, 16, 24, 32, 48, 64]) {
  const ms = run(`wordbomb-n${n}`, wordbomb(n), { reps: 2 });
  if (ms > ABORT_MS) break;
}
